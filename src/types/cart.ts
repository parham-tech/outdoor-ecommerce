/**
 * Cart domain types and state contracts for the ALTITUDE storefront.
 */

/**
 * Minimal persisted schema stored in localStorage.
 * Only stable identifiers and selections are persisted; volatile attributes
 * (price, name, image, stock limits) are resolved dynamically upon hydration.
 */
export interface PersistedCartItem {
  productId: string;
  slug: string;
  selectedColor?: string;
  selectedCapacity?: string;
  quantity: number;
}

/**
 * Result of stock availability resolution for a product.
 * Distinguishes between active availability status and exact inventory counts.
 */
export interface StockResolution {
  /** True if the product is purchasable in the storefront */
  isAvailable: boolean;
  /** Maximum quantity a user can select in this session */
  maxSelectableQuantity: number;
  /** True if exact numerical inventory was provided by the authoritative storefront source */
  hasExactInventory: boolean;
  /** Exact numerical inventory count if available */
  exactInventory?: number;
  /** Explanatory status label */
  statusReason?: string;
}

/**
 * Hydrated cart line item representing an enriched item in active state.
 * Uses a collision-safe deterministic composite identifier.
 */
export interface CartItem {
  /** Deterministic URI composite key: createCartItemId(productId, color, capacity) */
  id: string;
  productId: string;
  slug: string;
  name: string;
  category: string;
  /** Live unit price represented strictly in integer cents (e.g. 32900 for $329.00) */
  priceInCents: number;
  imageUrl: string;
  selectedColor?: string;
  selectedCapacity?: string;
  /** Active selected quantity (guaranteed positive integer >= 1) */
  quantity: number;
  /** Resolved upper selection bound */
  maxSelectableQuantity: number;
  /** Live availability status */
  isAvailable: boolean;
  /** Inventory precision tracking */
  hasExactInventory: boolean;
  exactInventory?: number;
  sku?: string;
}

/**
 * User-facing feedback notifications generated by the cart system
 * (e.g. stock clamping, item removal due to unavailability).
 */
export interface CartNotification {
  id: string;
  type: 'info' | 'warning' | 'error';
  message: string;
}

/**
 * Payload required to add an item to the shopping cart.
 */
export interface AddItemPayload {
  productId: string;
  slug: string;
  quantity: number;
  selectedColor?: string;
  selectedCapacity?: string;
}

import type { CartPricingSummary } from '@/lib/pricing/cartPricing';
export type { CartPricingSummary } from '@/lib/pricing/cartPricing';

/**
 * Public contract exposed by CartContext and useCart() hook.
 */
export interface CartContextValue {
  items: CartItem[];
  itemCount: number;
  subtotalInCents: number;
  pricing: CartPricingSummary;
  isDrawerOpen: boolean;
  isHydrated: boolean;
  notification: CartNotification | null;
  openDrawer: () => void;
  closeDrawer: () => void;
  toggleDrawer: () => void;
  clearNotification: () => void;
  addItem: (payload: AddItemPayload) => boolean;
  removeItem: (id: string) => void;
  updateQuantity: (id: string, quantity: number) => void;
  clearCart: () => void;
}
